#!/usr/bin/env node
// Writes the precache list and cache version into sw.js, between its GENERATED markers.
//
//   node tools/build-precache.mjs           # rewrite sw.js
//   node tools/build-precache.mjs --check   # exit 1 if sw.js is out of date (no write)
//   npm run precache
//
// What ships: the HTML pages in the repo root, the web manifest, and everything under css/, js/
// and icons/ (and any other top-level folder that is not on the skip list below), limited to web
// file types. Tests, docs, tools, dotfiles, package files and sw.js itself are skipped. New files
// are picked up automatically; re-run this before each release. The cache version is a hash of
// every shipped file's path and bytes, so any change to a shipped file gives a new cache.

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, sep, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SKIP_DIRS = new Set(['node_modules', 'test', 'tests', 'docs', 'tools', 'out', 'coverage']);
export const SKIP_FILES = new Set(['sw.js', 'package.json', 'package-lock.json']);
export const SHIP_EXT = new Set([
  '.html', '.css', '.js', '.mjs', '.json', '.webmanifest', '.png', '.svg', '.jpg', '.jpeg', '.webp', '.ico', '.woff', '.woff2', '.wasm', '.txt',
]);
export const BEGIN = '// >>> GENERATED by tools/build-precache.mjs. Do not edit by hand.';
export const END = '// <<< GENERATED';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Sorted repo-relative paths with forward slashes.
export function listShippable(root = ROOT) {
  const out = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      if (name.startsWith('.')) continue;
      const full = join(dir, name);
      const st = statSync(full);
      if (st.isDirectory()) {
        if (!SKIP_DIRS.has(name)) walk(full);
      } else if (st.isFile()) {
        const rel = relative(root, full).split(sep).join('/');
        const ext = name.slice(name.lastIndexOf('.')).toLowerCase();
        if (!SHIP_EXT.has(ext)) continue;
        if (!rel.includes('/') && SKIP_FILES.has(name)) continue;
        out.push(rel);
      }
    }
  };
  walk(root);
  return out.sort();
}

export function hashFiles(files, root = ROOT) {
  const hash = createHash('sha256');
  for (const rel of files) {
    hash.update(rel);
    hash.update('\0');
    hash.update(readFileSync(join(root, rel)));
    hash.update('\0');
  }
  return hash.digest('hex').slice(0, 12);
}

// The list the worker caches: the shell URL './' first, then every file.
export function buildManifest(root = ROOT) {
  const files = listShippable(root);
  return { version: hashFiles(files, root), urls: ['./', ...files] };
}

export function renderBlock({ version, urls }) {
  return [
    BEGIN,
    `const CACHE_VERSION = '${version}';`,
    'const PRECACHE = [',
    ...urls.map((u) => `  '${u}',`),
    '];',
    END,
  ].join('\n');
}

export function applyBlock(swSource, block) {
  const a = swSource.indexOf(BEGIN);
  const b = swSource.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error('sw.js has no GENERATED block');
  return swSource.slice(0, a) + block + swSource.slice(b + END.length);
}

// Returns { ok, expected, actual } without writing.
export function checkSw(root = ROOT) {
  const swPath = join(root, 'sw.js');
  const current = readFileSync(swPath, 'utf8');
  const expected = applyBlock(current, renderBlock(buildManifest(root)));
  return { ok: expected === current, expected, actual: current };
}

export function writeSw(root = ROOT) {
  const { ok, expected } = checkSw(root);
  if (!ok) writeFileSync(join(root, 'sw.js'), expected);
  return !ok;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (process.argv.includes('--check')) {
    const { ok } = checkSw();
    console.log(ok ? 'sw.js is up to date.' : 'sw.js is stale. Run: npm run precache');
    process.exit(ok ? 0 : 1);
  }
  const changed = writeSw();
  const m = buildManifest();
  console.log(`${changed ? 'Updated' : 'Unchanged'} sw.js: ${m.urls.length} URLs, version ${m.version}.`);
}
